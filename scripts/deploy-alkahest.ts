/**
 * Plan A repair: deploy Alkahest to GenLayer Chain (4221) with alkahest-ts's bundled bytecode (no Foundry needed),
 * then regenerate packages/core/src/alkahest-bradbury.ts so core, the CLI, the viewer and deploy:judge all use it.
 *
 * Why: on Nov 9, 2026 the addresses in Alkahest's deployment_genlayer_bradbury.json had no code on 4221.
 * Env: DEPLOYER_KEY (with GEN on GenLayer Chain), optional GENLAYER_CHAIN_RPC.
 * Deploys EAS + SchemaRegistry, the arbiters (TrustedOracleArbiter among them) and the obligations
 * (ERC20EscrowObligation, CommitRevealObligation, ...). Re-run scripts/day1-gate.sh afterwards.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { deployAlkahest } from "alkahest-ts";
import { createWalletClient, getAddress, http, publicActions, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { genlayerChain } from "../packages/core/src/chains.js";

const key = process.env.DEPLOYER_KEY;
if (!key) throw new Error("Set DEPLOYER_KEY (a testnet key with GEN on GenLayer Chain)");
const deployer = createWalletClient({
  account: privateKeyToAccount((key.startsWith("0x") ? key : `0x${key}`) as Hex),
  chain: genlayerChain,
  transport: http(),
}).extend(publicActions);

let n = 0;
const deployFn = async (abi: any[], bytecode: Hex, args: any[]) => {
  const hash = await deployer.deployContract({ abi, bytecode, args });
  const r = await deployer.waitForTransactionReceipt({ hash });
  if (r.status !== "success" || !r.contractAddress) throw new Error(`deploy #${n} failed in ${hash}`);
  n++;
  process.stdout.write(".");
  return r.contractAddress;
};

console.log(`Deploying Alkahest to chain ${genlayerChain.id} from ${deployer.account.address}`);
const arbiters = await deployAlkahest(deployFn, { eas: true, scope: "arbiters" });
const obligations = await deployAlkahest(deployFn, {
  scope: "obligations",
  easAddress: arbiters.eas,
  easSrAddress: arbiters.easSchemaRegistry,
});
const all = { ...arbiters, ...obligations } as Record<string, string>;
console.log(`\n${n} contracts deployed.`);

const pick = [
  "eas",
  "easSchemaRegistry",
  "erc20EscrowObligation",
  "erc20PaymentObligation",
  "nativeTokenEscrowObligation",
  "commitRevealObligation",
  "stringObligation",
  "trustedOracleArbiter",
  "trivialArbiter",
] as const;
const lines = pick.filter((k) => all[k]).map((k) => `  ${k}: "${getAddress(all[k]!)}",`);
const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL("../packages/core/src/alkahest-bradbury.ts", import.meta.url),
  `// Generated by scripts/deploy-alkahest.ts. Do not edit by hand; re-run the script after a redeploy.
// Deployed with alkahest-ts 1.1.2 bytecode to GenLayer Chain (4221) from ${deployer.account.address} on ${today}.
export const ALKAHEST_BRADBURY_DEPLOYMENT = {
  source: "scripts/deploy-alkahest.ts (alkahest-ts 1.1.2)",
  deployedAt: "${today}",
  verified: true,
} as const;

export const ALKAHEST_BRADBURY = {
${lines.join("\n")}
} as const;
`,
);
mkdirSync(new URL("../deployments/", import.meta.url), { recursive: true });
writeFileSync(new URL("../deployments/alkahest-bradbury.json", import.meta.url), JSON.stringify(all, null, 2) + "\n");
console.log("Wrote packages/core/src/alkahest-bradbury.ts and deployments/alkahest-bradbury.json.");
console.log("Next: pnpm build && pnpm gate && pnpm deploy:judge (BenchJudge must be deployed with these addresses).");
